# Comparison Operators
print('Comparison Operators')
2 == 2 # Equal to
2 != 1 # Not equal to
2 > 1 # Greater than
1 < 2 # Less than
2 >= 1 # Greater than or equal to
1 <= 2 # Less than or equal to

# == for conditions
# = for assignment


# Boolean Operators

# "and"/ binary operator
# takes two Boolean values
# expression = True if both values are True
print('\nand Boolean Operator')
1 == 1 # True
1 == 2 # False
1 == 1 and 1 == 2 # False

# 'and' operator Truth Table 
True and True # True
True and False # False
False and True  # False
False and False # False

# "or" / binary operator
# takes two Boolean values
# expression = True if either of two values is True
# if both are false = False
print('\nor Boolean Operator')
False or True # True
False or False # False

# 'or' operator Truth Table
True or True # True
True or False # True
False or True # True
False or False # False

# 'not'/ unary operator
# one Boolean value only
print('\nnot Boolean Operator')
not True # False
not False # True

